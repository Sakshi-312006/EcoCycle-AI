class VoiceService:
    """Service providing regional language instructions and Bhashini interface."""

    @staticmethod
    def get_supported_languages() -> List[SupportedLanguage]:
        """Return all supported Indian regional and official languages."""
        return SUPPORTED_LANGUAGES

    @staticmethod
    def get_instructions(lang: LanguageCodeEnum) -> LocalizedInstructionResponse:
        """Return localized segregation rules for specified language."""
        lang_code = lang.value
        data = LOCALIZED_INSTRUCTIONS.get(lang_code, LOCALIZED_INSTRUCTIONS["en"])
        return LocalizedInstructionResponse(
            language_code=lang_code,
            language_name=data["language_name"],
            general_guideline=data["general_guideline"],
            streams=data["streams"],
        )

    @staticmethod
    def get_ui_bundle(lang: LanguageCodeEnum) -> UIBundleResponse:
        """Return full multilingual UI bundle with UI strings and visual stream guidance."""
        lang_code = lang.value
        instructions_data = LOCALIZED_INSTRUCTIONS.get(lang_code, LOCALIZED_INSTRUCTIONS["en"])
        lang_meta = next((l for l in SUPPORTED_LANGUAGES if l.code.value == lang_code), SUPPORTED_LANGUAGES[0])
        strings = UI_STRINGS.get(lang_code, UI_STRINGS["en"])
        return UIBundleResponse(
            language_code=lang_code,
            language_name=instructions_data["language_name"],
            bcp47_tag=lang_meta.bcp47_tag,
            ui_strings=strings,
            streams=instructions_data["streams"],
        )

    @staticmethod
    def check_bhashini_status() -> BhashiniIntegrationStatus:
        """Probe MeitY Bhashini integration interface status honestly without fake claims."""
        has_credentials = bool(settings.BHASHINI_API_KEY and settings.BHASHINI_USER_ID)

        if not has_credentials:
            return BhashiniIntegrationStatus(
                status="unconfigured",
                configured_credentials=False,
                message="MeitY Bhashini credentials (BHASHINI_API_KEY / BHASHINI_USER_ID) are not configured in .env. Live speech recognition and neural translation interfaces remain dormant.",
            )

        # In prototype stage, if credentials are set, indicate ready for live endpoint verification
        return BhashiniIntegrationStatus(
            status="configured_untested",
            configured_credentials=True,
            message="Bhashini credentials detected. Ready for live handshake verification.",
        )
